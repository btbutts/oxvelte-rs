    /// One expected diagnostic from a fixture's `-errors.yaml` (upstream
    /// ESLint convention: 1-based line, 1-based UTF-16 column), surfaced
    /// through the manifest.
    #[derive(serde::Deserialize)]
    struct FixtureExpectedError {
        message: String,
        line: usize,
        column: usize,
    }

    /// A single case from the fixture manifest generated by
    /// `cargo get-eslint-fixtures` — the single source of truth for case
    /// discovery, configuration and expectations
    /// (see docs/research/test/pinned-rules.md).
    #[derive(serde::Deserialize)]
    #[serde(rename_all = "camelCase")]
    struct FixtureCase {
        id: String,
        rule: String,
        kind: String,
        filename: String,
        config: serde_json::Value,
        config_file: Option<String>,
        executable_config: bool,
        ineligible: Vec<String>,
        requirements: serde_json::Value,
        errors: Vec<FixtureExpectedError>,
    }

    fn fixture_cases() -> &'static [FixtureCase] {
        static CASES: std::sync::OnceLock<Vec<FixtureCase>> = std::sync::OnceLock::new();
        CASES.get_or_init(|| {
            let text = std::fs::read_to_string("fixtures/linter/manifest.json")
                .expect("fixtures/linter/manifest.json missing; run `cargo get-eslint-fixtures`");
            let manifest: serde_json::Value = serde_json::from_str(&text).unwrap();
            serde_json::from_value(manifest["cases"].clone()).unwrap()
        })
    }

    /// Eligible manifest cases for one rule and kind. Cases gated to a
    /// different toolchain (ineligible under the pinned environment) are
    /// skipped here; the version matrix exercises them per profile. The
    /// type-analysis fixtures under `typescript/` (and `ts/` for
    /// valid-compile) are covered by the upstream parity suite instead.
    fn manifest_cases(rule_name: &str, kind: &str) -> Vec<&'static FixtureCase> {
        fixture_cases()
            .iter()
            .filter(|case| {
                case.rule == rule_name
                    && case.kind == kind
                    && case.ineligible.is_empty()
                    && !case.filename.contains("/typescript/")
                    && !(rule_name == "valid-compile" && case.filename.contains("/ts/"))
            })
            .collect()
    }

    /// Fixture configs written against upstream's repo layout embed
    /// `tests/fixtures/...` paths (SvelteKit `files.routes` settings); map
    /// that virtual prefix onto the case's real location.
    fn rewrite_fixture_paths(config: &serde_json::Value, filename: &str) -> serde_json::Value {
        let root = filename.split('/').next().unwrap_or("upstream");
        let prefix = format!("fixtures/linter/{root}");
        let mut config = config.clone();
        for pointer in [
            "/settings/svelte/kit/files/routes",
            "/languageOptions/parserOptions/svelteConfig/kit/files/routes",
        ] {
            let rewritten = config
                .pointer(pointer)
                .and_then(|value| value.as_str())
                .and_then(|routes| {
                    routes
                        .strip_prefix("tests/fixtures/rules")
                        .or_else(|| routes.strip_prefix("tests/fixtures"))
                        .map(|rest| format!("{prefix}{rest}"))
                });
            if let Some(rewritten) = rewritten {
                *config.pointer_mut(pointer).unwrap() = serde_json::json!(rewritten);
            }
        }
        config
    }

    /// Expectations were recorded against upstream's repository layout;
    /// normalize real paths in messages back to the virtual fixture path.
    fn normalize_messages(diags: &mut [LintDiagnostic], file_path: &str, case: &FixtureCase) {
        let virtual_path = format!("tests/fixtures/rules/{}", case.id);
        for diag in diags {
            diag.message = diag.message.replace(file_path, &virtual_path);
        }
    }

    /// Build the rule config for a case from the manifest's recorded
    /// configuration: rule options, settings, and compiler parser wiring.
    /// Executable (JS/CJS) fixture configs load through the compiler bridge.
    fn config_for_case(case: &FixtureCase) -> RuleConfig {
        if case.executable_config {
            let path = std::fs::canonicalize(format!(
                "fixtures/linter/{}",
                case.config_file.as_deref().unwrap()
            ))
            .unwrap();
            return RuleConfig {
                options: None,
                settings: Some(serde_json::json!({"compiler":{"executableConfigPath": path.to_string_lossy().trim_start_matches(r"\\?\").replace('\\',"/")}})),
            };
        }
        let config = &rewrite_fixture_paths(&case.config, &case.filename);
        let options = config.get("options").cloned().or_else(|| {
            // ESLint format: { "rules": { "svelte/rule-name": ["error", options] } }
            config.get("rules").and_then(|r| {
                r.as_object().and_then(|m| {
                    m.values()
                        .next()
                        .and_then(|v| v.as_array().and_then(|a| a.get(1).cloned()))
                })
            })
        });
        let mut settings = config.get("settings").cloned();
        if let Some(parser_options) = config.pointer("/languageOptions/parserOptions") {
            let settings = settings.get_or_insert_with(|| serde_json::json!({}));
            settings["compiler"] = serde_json::json!({});
            if let Some(parser) = parser_options.get("parser") {
                settings["compiler"]["parser"] = parser.clone();
            }
            if let Some(svelte_config) = parser_options.get("svelteConfig") {
                settings["compiler"]["svelteConfig"] = svelte_config.clone();
            }
            if parser_options.pointer("/ecmaFeatures/globalReturn") == Some(&serde_json::json!(true))
            {
                settings["parserOptions"] =
                    serde_json::json!({"ecmaFeatures": {"globalReturn": true}});
            }
        }
        RuleConfig { options, settings }
    }

    fn lint_fixture_file(
        lint: &Linter,
        source: &str,
        config: RuleConfig,
        file_path: &str,
    ) -> Vec<LintDiagnostic> {
        if file_path.ends_with(".svelte") {
            let alloc = oxc::allocator::Allocator::default();
            let result = parser::parse(source, &alloc);
            lint.lint_with_config_and_path(&result.ast, source, config, file_path)
        } else if file_path.ends_with(".svelte.js") || file_path.ends_with(".svelte.ts") {
            let is_ts = file_path.ends_with(".ts");
            lint.lint_svelte_script_with_config_and_path(source, is_ts, config, file_path)
        } else {
            lint.lint_script_with_config_and_path(source, config, file_path)
        }
    }

    /// 1-based line and 1-based UTF-16 column of a byte offset, matching the
    /// positions recorded in the `-errors.yaml` files.
    fn fixture_line_col(source: &str, offset: usize) -> (usize, usize) {
        let mut line = 1usize;
        let mut col = 1usize;
        for (i, ch) in source.char_indices() {
            if i >= offset {
                break;
            }
            if ch == '\n' {
                line += 1;
                col = 1;
            } else {
                col += ch.len_utf16();
            }
        }
        (line, col)
    }

    /// Assert a rule's diagnostics on an invalid fixture against the
    /// manifest's expectations exactly (count, order, message, line, column).
    fn assert_invalid_fixture(
        rule_name: &str,
        path: &str,
        source: &str,
        expected: &[FixtureExpectedError],
        rule_diags: &[&LintDiagnostic],
    ) {
        // Test-only maintenance aid: `OXVELTE_DUMP_FIXTURE=1 cargo test --lib`
        // prints each invalid fixture's actual diagnostics as YAML, for
        // reviewing or regenerating `-errors.yaml` expectations.
        if std::env::var_os("OXVELTE_DUMP_FIXTURE").is_some() {
            eprintln!("--- {path} (rule {rule_name})");
            for d in rule_diags {
                let (line, col) = fixture_line_col(source, d.span.start as usize);
                eprintln!(
                    "- message: {:?}\n  line: {line}\n  column: {col}\n  suggestions: null",
                    d.message
                );
            }
        }
        assert!(
            !expected.is_empty(),
            "Rule {rule_name} manifest case {path} has no expected diagnostics"
        );
        for (i, exp) in expected.iter().enumerate() {
            let Some(diag) = rule_diags.get(i) else {
                panic!(
                    "Rule {rule_name} fixture {path} produced only {} diagnostic(s); missing:\n\
                        expected fixture error: {} at {}:{}",
                    rule_diags.len(),
                    exp.message,
                    exp.line,
                    exp.column
                );
            };
            let (line, col) = fixture_line_col(source, diag.span.start as usize);
            if exp.message != diag.message || exp.line != line || exp.column != col {
                panic!(
                    "Rule {rule_name} fixture {path} diagnostic #{} mismatch:\n\
                        expected fixture error: {} at {}:{}\n\
                        our actual fixture error: {} at {}:{}",
                    i + 1,
                    exp.message,
                    exp.line,
                    exp.column,
                    diag.message,
                    line,
                    col
                );
            }
        }
        if rule_diags.len() > expected.len() {
            let extra = rule_diags[expected.len()];
            let (line, col) = fixture_line_col(source, extra.span.start as usize);
            panic!(
                "Rule {rule_name} fixture {path} produced {} diagnostic(s) but {} were \
                    expected; first extra:\nour actual fixture error: {} at {}:{}",
                rule_diags.len(),
                expected.len(),
                extra.message,
                line,
                col
            );
        }
    }

    fn run_linter_valid(rule_name: &str) {
        let lint = Linter::all();
        for case in manifest_cases(rule_name, "valid") {
            if !compiler_fixture_is_eligible(case) {
                continue;
            }
            let file_path = format!("fixtures/linter/{}", case.filename);
            let source = std::fs::read_to_string(&file_path).unwrap();
            let mut diags = lint_fixture_file(&lint, &source, config_for_case(case), &file_path);
            normalize_messages(&mut diags, &file_path, case);
            let rule_diags: Vec<_> = diags
                .iter()
                .filter(|d| d.rule_name == format!("svelte/{}", rule_name))
                .collect();
            assert!(
                rule_diags.is_empty(),
                "Rule {} should not fire on valid file {}: {:?}",
                rule_name,
                file_path,
                rule_diags.iter().map(|d| &d.message).collect::<Vec<_>>()
            );
        }
    }

    fn run_linter_invalid(rule_name: &str) {
        let lint = Linter::all();
        for case in manifest_cases(rule_name, "invalid") {
            if !compiler_fixture_is_eligible(case) {
                continue;
            }
            let file_path = format!("fixtures/linter/{}", case.filename);
            let source = std::fs::read_to_string(&file_path).unwrap();
            let mut diags = lint_fixture_file(&lint, &source, config_for_case(case), &file_path);
            normalize_messages(&mut diags, &file_path, case);
            let rule_diags: Vec<_> = diags
                .iter()
                .filter(|d| d.rule_name == format!("svelte/{}", rule_name))
                .collect();
            assert_invalid_fixture(rule_name, &file_path, &source, &case.errors, &rule_diags);
        }
    }

    fn run_linter_invalid_fixture(rule_name: &str, filename: &str) {
        let lint = Linter::all();
        let case = fixture_cases()
            .iter()
            .find(|case| case.rule == rule_name && case.filename == filename)
            .unwrap_or_else(|| panic!("no manifest case for {filename}"));
        let file_path = format!("fixtures/linter/{}", case.filename);
        let source = std::fs::read_to_string(&file_path).unwrap();
        let mut diags = lint_fixture_file(&lint, &source, config_for_case(case), &file_path);
        normalize_messages(&mut diags, &file_path, case);
        let rule_diags: Vec<_> = diags
            .iter()
            .filter(|d| d.rule_name == format!("svelte/{}", rule_name))
            .collect();
        assert_invalid_fixture(rule_name, &file_path, &source, &case.errors, &rule_diags);
    }

    // Older local copies retain fixtures for Svelte 3/4. Compiler behavior
    // follows the installed version, so respect their declared major ranges.
    fn compiler_fixture_is_eligible(case: &FixtureCase) -> bool {
        if !matches!(case.rule.as_str(), "valid-compile" | "no-unused-svelte-ignore") {
            return true;
        }
        let Some(range) = case.requirements.get("svelte").and_then(|v| v.as_str()) else {
            return true;
        };
        let version = crate::compiler::compile(
            "",
            Some(&format!("fixtures/linter/{}", case.filename)),
            None,
        )
        .expect("Compiler fixtures require Node and an installed Svelte compiler")
        .svelte_major;
        crate::linter::npm_range_may_include_major(range, version as u8)
    }

